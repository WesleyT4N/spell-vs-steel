// Render the soundtrack (songs.mjs) with the MuseScore General soundfont and write src/engine/musicTracks.ts.
// Setup (once): cd scripts/music && npm install    (needs ffmpeg with libmp3lame on PATH)
// Run: node gen.mjs [track ...]     (MP3s also land in scripts/music/out/ for listening)
import fs from 'node:fs';
import { renderLoop } from './lib.mjs';
import { STAGES, menu, victory } from './songs.mjs';

const here = new URL('.', import.meta.url).pathname;
const outDir = here + 'out';
fs.mkdirSync(outDir, { recursive: true });
const songs = { menu, victory, ...Object.fromEntries(Object.entries(STAGES).map(([k, f]) => [`stage_${k}`, f])) };
const only = process.argv.slice(2);
const meta = {};
for (const [id, f] of Object.entries(songs)) {
  const file = `${outDir}/${id}.mp3`;
  if (only.length && !only.includes(id) && fs.existsSync(file + '.json')) { meta[id] = JSON.parse(fs.readFileSync(file + '.json', 'utf8')); continue; }
  const r = await renderLoop(f(), file, { bitrate: '48k' });
  meta[id] = { loopStart: +r.loopStart.toFixed(5), loopEnd: +r.loopEnd.toFixed(5) };
  fs.writeFileSync(file + '.json', JSON.stringify(meta[id]));
  console.log(id.padEnd(18), `${(r.bytes / 1024).toFixed(0)} KB`, `${r.dur.toFixed(1)}s`, `loop ${r.loopStart.toFixed(2)}-${r.loopEnd.toFixed(2)}`);
}
const lines = Object.entries(meta).map(([id, m]) => `  ${id}: { loopStart: ${m.loopStart}, loopEnd: ${m.loopEnd}, mp3: '${fs.readFileSync(`${outDir}/${id}.mp3`).toString('base64')}' },`);
fs.writeFileSync(here + '../../src/engine/musicTracks.ts', `// Generated by scripts/music/gen.mjs from scripts/music/songs.mjs (MuseScore General soundfont, MP3). Do not edit by hand.
/** Looping BGM: base64 MP3s with loop points in seconds (loopEnd 0 = play once). */
export const TRACKS = {
${lines.join('\n')}
} satisfies Record<string, { loopStart: number; loopEnd: number; mp3: string }>;
export type TrackId = keyof typeof TRACKS;
`);
