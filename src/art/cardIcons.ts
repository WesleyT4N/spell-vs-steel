export const hasCardIcon = (id: string): boolean => id in ICONS;

const cache = new Map<string, HTMLCanvasElement>();

/** The outlined 18x18 icon for a spell, or null if it has none. */
export function cardIconCanvas(id: string, el: Element): HTMLCanvasElement | null {
  const rows = ICONS[id];
  if (!rows) return null;
  let o = cache.get(id);
  if (o) return o;
  const pal: Record<string, string> = { ...FIXED, 1: ELEMENT_RAMP[el][0], 2: ELEMENT_RAMP[el][1], 3: ELEMENT_RAMP[el][2] };
  const n = ICON_SIZE, filled = (x: number, y: number): boolean => rows[y - 1]?.[x - 1] !== undefined && rows[y - 1][x - 1] !== '.';
  o = document.createElement('canvas');
  o.width = o.height = n;
  const c = o.getContext('2d')!;
  for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
    let col: string | undefined;
    if (filled(x, y)) col = pal[rows[y - 1][x - 1]] ?? '#ff00ff';
    else if (filled(x + 1, y) || filled(x - 1, y) || filled(x, y + 1) || filled(x, y - 1)) col = '#000000';
    if (col) { c.fillStyle = col; c.fillRect(x, y, 1, 1); }
  }
  cache.set(id, o);
  return o;
}
