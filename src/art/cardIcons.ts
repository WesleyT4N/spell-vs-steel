const cache = new Map<string, HTMLCanvasElement>();

/** The spell's icon, or null if it has none. */
export function cardIconCanvas(id: string): HTMLCanvasElement | null {
  const def = ICONS[id];
  if (!def) return null;
  let o = cache.get(id);
  if (o) return o;
  o = document.createElement('canvas');
  o.width = o.height = ICON_SIZE;
  const c = o.getContext('2d')!;
  def.rows.forEach((r, y) => [...r].forEach((ch, x) => {
    if (ch === '.') return;
    c.fillStyle = def.pal[ch.charCodeAt(0) - 97];
    c.fillRect(x, y, 1, 1);
  }));
  cache.set(id, o);
  return o;
}
