"""Build src/art/cardArt.ts from the picked PixelLab spell icons.

Input: <src>/cards/<id>.png, one 40x40 create_image_pixen result per spell (art/pixellab/cards in the project
files; prompts in tools/pixellab/card_icons.json). 40px is the card frame's art box at 2 UI pixels per art pixel
of the old 20px icons, so the HD icon sits at the same density as the 48px fighters. Each icon is quantized to its
own palette of at most 24 colours (index 0 = the darkest, its outline) and written as palette-letter rows.
Usage: python3 tools/pixellab/build_card_icons.py [src]
"""
import sys, os, json
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else '/mnt/project-files/art/pixellab'
HERE = os.path.dirname(__file__)
DST = os.path.join(HERE, '../../src/art/cardArt.ts')
ALPHA = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'
COLORS = 24
IDS = list(json.load(open(os.path.join(HERE, 'card_icons.json'))))

def build(cid):
  im = Image.open(f'{SRC}/cards/{cid}.png').convert('RGBA')
  assert im.size == (40, 40), (cid, im.size)
  A = [a >= 128 for a in im.getchannel('A').get_flattened_data()]
  rgb = Image.new('RGB', im.size, (0, 0, 0)); rgb.paste(im, mask=im.getchannel('A'))
  q = rgb.quantize(colors=COLORS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
  qpal = q.getpalette(); qd = list(q.get_flattened_data()); W, H = im.size
  used = sorted({qd[i] for i in range(len(qd)) if A[i]})
  cols = [tuple(qpal[3 * u:3 * u + 3]) for u in used]
  order = sorted(range(len(cols)), key=lambda i: sum(cols[i]))  # darkest first: the outline
  remap = {used[o]: n for n, o in enumerate(order)}
  pal = ['#%02x%02x%02x' % cols[o] for o in order]
  rows = [''.join(ALPHA[remap[qd[y * W + x]]] if A[y * W + x] else '.' for x in range(W)) for y in range(H)]
  return pal, rows

out = ["// HD spell icons for the card frames: PixelLab art (40x40) as palette-letter rows ('.' = empty), drawn at the",
       "// same density as the 48px fighters. Generated by tools/pixellab/build_card_icons.py; do not edit by hand.",
       "export interface CardArt { pal: string[]; rows: string[] }",
       "/** HD icon pixels per old 20px icon pixel. */",
       "export const CARD_ART_RES = 2;",
       "export const CARD_ART: Record<string, CardArt> = {"]
for cid in IDS:
  pal, rows = build(cid)
  out += [f"  {cid}: {{", f"    pal: {pal!r},", "    rows: ["] + [f"      '{r}'," for r in rows] + ["    ],", "  },"]
out += ["};", ""]
open(DST, 'w').write('\n'.join(out))
print(len(IDS), 'icons ->', DST, os.path.getsize(DST) // 1024, 'KB')
